from sortedcontainers import SortedList

# ============================================================
# 基本操作
# ============================================================

sl = SortedList()

# 追加: O(log n)
sl.add(5)
sl.add(3)
sl.add(8)
sl.add(3)  # 重複OK → [3, 3, 5, 8]

# 削除: O(log n)
sl.remove(3)       # 1つ削除。存在しないと ValueError
sl.discard(100)    # 存在しなくてもエラーにならない
sl.pop(0)          # 最小値を削除して返す
sl.pop(-1)         # 最大値を削除して返す
sl.pop()           # 最大値を削除して返す（引数なし = -1）

# ============================================================
# インデックスアクセス: O(log n)
# ============================================================

sl = SortedList([10, 20, 30, 40, 50])

sl[0]    # 最小値 → 10
sl[-1]   # 最大値 → 50
sl[2]    # 3番目に小さい値 → 30

# ============================================================
# 二分探索: O(log n)
# ============================================================

sl = SortedList([1, 3, 3, 5, 7])

sl.bisect_left(3)   # 3以上の最初のindex → 1
sl.bisect_right(3)  # 3より大きい最初のindex → 3

sl.bisect_left(4)   # 4以上の最初のindex → 3
sl.bisect_right(4)  # 4より大きい最初のindex → 3（4は存在しないので同じ）

# x未満の個数
sl.bisect_left(5)   # → 3

# x以下の個数
sl.bisect_right(5)  # → 4

# x以上の個数
len(sl) - sl.bisect_left(5)  # → 2

# xより大きい個数
len(sl) - sl.bisect_right(5)  # → 1

# ============================================================
# 存在判定・個数: O(log n)
# ============================================================

sl = SortedList([1, 3, 3, 5])

3 in sl       # → True
sl.count(3)   # → 2
sl.index(3)   # 最初に現れるindex → 1（存在しないと ValueError）

# ============================================================
# 最小値・最大値に近い値を探す
# ============================================================

sl = SortedList([10, 20, 30, 40, 50])

# x以上の最小値
def ge(sl, x):
    i = sl.bisect_left(x)
    return sl[i] if i < len(sl) else None

# xより大きい最小値
def gt(sl, x):
    i = sl.bisect_right(x)
    return sl[i] if i < len(sl) else None

# x以下の最大値
def le(sl, x):
    i = sl.bisect_right(x) - 1
    return sl[i] if i >= 0 else None

# x未満の最大値
def lt(sl, x):
    i = sl.bisect_left(x) - 1
    return sl[i] if i >= 0 else None

